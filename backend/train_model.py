import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingRegressor, RandomForestRegressor
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.pipeline import Pipeline
from sklearn.tree import DecisionTreeRegressor

from preprocess import (
    MODEL_DIR,
    MODEL_PATH,
    METADATA_PATH,
    build_preprocessor,
    get_train_test_data,
    save_metadata,
)


MODEL_CONFIG = {
    "Linear Regression": LinearRegression(),
    "Decision Tree Regressor": DecisionTreeRegressor(random_state=42),
    "Random Forest Regressor": RandomForestRegressor(n_estimators=200, random_state=42),
    "Gradient Boosting Regressor": GradientBoostingRegressor(random_state=42),
}


def compute_metrics(y_true, y_pred):
    return {
        "mae": float(mean_absolute_error(y_true, y_pred)),
        "mse": float(mean_squared_error(y_true, y_pred)),
        "rmse": float(np.sqrt(mean_squared_error(y_true, y_pred))),
        "r2": float(r2_score(y_true, y_pred)),
    }


def train_and_evaluate():
    X_train, X_test, y_train, y_test, cleaned_df = get_train_test_data()

    model_metrics = {}
    model_predictions = {}

    for model_name, model in MODEL_CONFIG.items():
        pipeline = Pipeline([
            ("preprocessor", build_preprocessor()),
            ("model", model),
        ])
        pipeline.fit(X_train, y_train)
        predictions = pipeline.predict(X_test)
        model_predictions[model_name] = predictions
        model_metrics[model_name] = compute_metrics(y_test, predictions)

    best_model_name = max(
        model_metrics,
        key=lambda key: model_metrics[key]["r2"],
    )
    best_pipeline = Pipeline([
        ("preprocessor", build_preprocessor()),
        ("model", MODEL_CONFIG[best_model_name]),
    ])
    best_pipeline.fit(X_train, y_train)

    MODEL_DIR.mkdir(exist_ok=True, parents=True)
    joblib.dump(best_pipeline, MODEL_PATH)

    metadata = {
        "dataset_name": "house_prices.csv",
        "training_records": int(len(X_train)),
        "testing_records": int(len(X_test)),
        "total_records": int(len(cleaned_df)),
        "columns": list(cleaned_df.columns),
        "locations": sorted(cleaned_df["location"].unique().tolist()),
        "features": ["bedrooms", "sqft", "bathrooms", "property_age", "parking", "stories", "location"],
        "best_model": best_model_name,
        "best_r2": model_metrics[best_model_name]["r2"],
        "model_metrics": model_metrics,
        "feature_importance": {},
        "disclaimer": "Predicted values are estimates generated by a machine learning model and should not be considered professional property valuation.",
    }

    if hasattr(best_pipeline.named_steps["model"], "feature_importances_"):
        importances = best_pipeline.named_steps["model"].feature_importances_
        feature_names = list(best_pipeline.named_steps["preprocessor"].get_feature_names_out())
        metadata["feature_importance"] = {
            name: float(value)
            for name, value in zip(feature_names, importances)
        }

    save_metadata(metadata)
    return metadata


if __name__ == "__main__":
    metadata = train_and_evaluate()
    print("Best model:", metadata["best_model"])
    print("Best R²:", round(metadata["best_r2"], 4))
    print("Metrics:")
    for name, metrics in metadata["model_metrics"].items():
        print(f"- {name}: MAE={metrics['mae']:.2f}, MSE={metrics['mse']:.2f}, RMSE={metrics['rmse']:.2f}, R²={metrics['r2']:.4f}")
