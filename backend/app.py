import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from flask import Flask, jsonify, request, send_from_directory

from preprocess import DATASET_PATH, METADATA_PATH, clean_dataset, get_train_test_data


PROJECT_ROOT = Path(__file__).resolve().parent.parent
FRONTEND_DIR = PROJECT_ROOT / "frontend"
MODEL_PATH = PROJECT_ROOT / "model" / "house_price_model.pkl"

app = Flask(__name__, static_folder=str(FRONTEND_DIR), static_url_path="")


def format_indian_price(value):
    value = float(value)
    if value >= 10000000:
        return f"₹{value / 10000000:.2f} Crores"
    return f"₹{value / 100000:.2f} Lakhs"


def load_model():
    if not MODEL_PATH.exists():
        raise FileNotFoundError("Model file not found. Please train the model first.")
    return joblib.load(MODEL_PATH)


@app.route("/")
def index():
    return send_from_directory(FRONTEND_DIR, "index.html")


@app.route("/predict")
def predict_page():
    return send_from_directory(FRONTEND_DIR, "predict.html")


@app.route("/analytics")
def analytics_page():
    return send_from_directory(FRONTEND_DIR, "analytics.html")


@app.route("/about")
def about_page():
    return send_from_directory(FRONTEND_DIR, "about.html")


@app.route("/api/locations")
def api_locations():
    try:
        df = clean_dataset(pd.read_csv(DATASET_PATH))
        locations = sorted(df["location"].dropna().unique().tolist())
        return jsonify({"locations": locations})
    except FileNotFoundError:
        return jsonify({"error": "Dataset not found."}), 404
    except Exception as exc:  # pragma: no cover
        return jsonify({"error": str(exc)}), 500


@app.route("/api/model-info")
def api_model_info():
    try:
        metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8")) if METADATA_PATH.exists() else {}
        df = clean_dataset(pd.read_csv(DATASET_PATH))
        response = {
            "dataset_records": int(len(df)),
            "locations": len(df["location"].unique()),
            "features": len(df.columns) - 1,
            "best_model": metadata.get("best_model", "N/A"),
            "best_r2": metadata.get("best_r2", 0.0),
            "disclaimer": metadata.get("disclaimer", "Predicted values are estimates generated by a machine learning model and should not be considered professional property valuation."),
        }
        return jsonify(response)
    except FileNotFoundError:
        return jsonify({"error": "Dataset or model metadata not found."}), 404
    except Exception as exc:  # pragma: no cover
        return jsonify({"error": str(exc)}), 500


@app.route("/api/analytics")
def api_analytics():
    try:
        metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8")) if METADATA_PATH.exists() else {}
        X_train, X_test, y_train, y_test, cleaned_df = get_train_test_data()
        model = load_model()
        y_pred = model.predict(X_test)

        model_metrics = metadata.get("model_metrics", {})
        comparison = [
            {
                "label": name,
                "r2": metrics.get("r2", 0.0),
                "mae": metrics.get("mae", 0.0),
                "rmse": metrics.get("rmse", 0.0),
            }
            for name, metrics in model_metrics.items()
        ]

        feature_importance = metadata.get("feature_importance", {})
        feature_importance_data = [
            {"label": key, "value": float(value)}
            for key, value in feature_importance.items()
        ]

        analytics = {
            "dataset_size": int(len(cleaned_df)),
            "training_records": int(len(X_train)),
            "testing_records": int(len(X_test)),
            "locations": int(cleaned_df["location"].nunique()),
            "features": int(len(cleaned_df.columns) - 1),
            "best_model": metadata.get("best_model", "N/A"),
            "best_r2": metadata.get("best_r2", 0.0),
            "mae": float(np.mean(np.abs(y_test - y_pred))),
            "rmse": float(np.sqrt(np.mean((y_test - y_pred) ** 2))),
            "model_comparison": comparison,
            "actual_vs_predicted": {
                "actual": y_test.round(2).tolist(),
                "predicted": y_pred.round(2).tolist(),
            },
            "feature_importance": feature_importance_data,
            "house_price_distribution": {
                "labels": ["Low", "Mid", "High"],
                "values": [
                    int((cleaned_df["price"] < cleaned_df["price"].quantile(0.33)).sum()),
                    int(((cleaned_df["price"] >= cleaned_df["price"].quantile(0.33)) & (cleaned_df["price"] <= cleaned_df["price"].quantile(0.66))).sum()),
                    int((cleaned_df["price"] > cleaned_df["price"].quantile(0.66)).sum()),
                ],
            },
            "price_vs_sqft": {
                "sqft": cleaned_df["sqft"].round(2).tolist(),
                "price": cleaned_df["price"].round(2).tolist(),
            },
            "disclaimer": metadata.get("disclaimer", "Predicted values are estimates generated by a machine learning model and should not be considered professional property valuation."),
        }
        return jsonify(analytics)
    except FileNotFoundError:
        return jsonify({"error": "Dataset or model not found. Please train the model first."}), 404
    except Exception as exc:  # pragma: no cover
        return jsonify({"error": str(exc)}), 500


@app.route("/api/predict", methods=["POST"])
def api_predict():
    try:
        payload = request.get_json(force=True, silent=True) or {}
        if not payload:
            return jsonify({"error": "No input data provided."}), 400

        required_fields = ["bedrooms", "sqft", "bathrooms", "location"]
        missing = [field for field in required_fields if field not in payload]
        if missing:
            return jsonify({"error": f"Missing required fields: {', '.join(missing)}"}), 400

        location = str(payload["location"]).strip().title()
        row = {
            "bedrooms": float(payload["bedrooms"]),
            "sqft": float(payload["sqft"]),
            "bathrooms": float(payload["bathrooms"]),
            "location": location,
            "property_age": float(payload.get("property_age", 10.0)),
            "parking": float(payload.get("parking", 1.0)),
            "stories": float(payload.get("stories", 1.0)),
        }

        model = load_model()
        metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8")) if METADATA_PATH.exists() else {}
        df = clean_dataset(pd.read_csv(DATASET_PATH))
        known_locations = set(df["location"].unique().tolist())

        if location not in known_locations:
            return jsonify({"error": f"Unknown location '{location}'. Choose one from the dataset."}), 400

        for key, value in row.items():
            if key in ["bedrooms", "sqft", "bathrooms", "property_age", "parking", "stories"]:
                if pd.isna(value) or value <= 0:
                    return jsonify({"error": f"Invalid value for {key}."}), 400

        input_frame = pd.DataFrame([row])
        prediction = float(model.predict(input_frame)[0])
        result = {
            "predicted_price": round(prediction, 2),
            "formatted_price": format_indian_price(prediction),
            "model_name": metadata.get("best_model", "Best model"),
            "model_r2": metadata.get("best_r2", 0.0),
            "disclaimer": metadata.get("disclaimer", "Predicted values are estimates generated by a machine learning model and should not be considered professional property valuation."),
        }
        return jsonify(result)
    except FileNotFoundError:
        return jsonify({"error": "Model file not found. Please train the model first."}), 404
    except ValueError as exc:
        return jsonify({"error": str(exc)}), 400
    except Exception as exc:  # pragma: no cover
        return jsonify({"error": str(exc)}), 500


if __name__ == "__main__":
    app.run(debug=True, host="0.0.0.0", port=5000)
